import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { examples } from '../demo/examples.js';
import { renderChemfig } from '../src/core.js';

const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
const slug = (name: string) => name.toLowerCase().replaceAll(' ', '-');
const escape = (value: string) =>
  value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const artifacts = new Map<string, string>();

for (const example of examples) {
  const { svg } = renderChemfig(example.source, { title: example.name, padding: 24 });
  artifacts.set(
    `assets/examples/${slug(example.name)}.svg`,
    svg.replace('<svg ', '<svg style="color:#1d2751;background:#fff" ') + '\n',
  );
}

// A fixed, self-contained contact sheet: no fonts, images, or services to fetch.
const featured = ['Aspirin', 'Caffeine', 'Lactic acid', 'Phenol', 'Acetate', 'Acetonitrile'];
const cells = featured.map((name, index) => {
  const example = examples.find((example) => example.name === name)!;
  const x = 32 + (index % 3) * 304;
  const y = 148 + Math.floor(index / 3) * 232;
  const { svg } = renderChemfig(example.source, { title: name, padding: 16 });
  const drawing = svg
    .replace('<svg ', `<svg x="${x + 12}" y="${y + 36}" `)
    .replace(/ width="[^"]*" height="[^"]*"/, ' width="264" height="164"');
  return `<g>
  <path d="M${x} ${y}h280" stroke="#d5deed"/>
  <text x="${x + 12}" y="${y + 27}" font-size="16" fill="#52627e">${escape(name)}</text>
  ${drawing}
</g>`;
});

artifacts.set(
  'assets/examples/gallery.svg',
  `<svg xmlns="http://www.w3.org/2000/svg" width="960" height="636" viewBox="0 0 960 636" role="img" aria-labelledby="title description" style="color:#1d2751;font-family:Arial,Helvetica,sans-serif">
<title id="title">Chemfig in. SVG out.</title>
<desc id="description">Aspirin, caffeine, lactic acid, phenol, acetate, and acetonitrile rendered by rehype-chemfig.</desc>
<rect width="960" height="636" rx="16" fill="#f4f7fc"/>
<text x="44" y="66" font-family="Trebuchet MS,Arial,sans-serif" font-size="38" font-weight="700" fill="#1d2751">Chemfig in. SVG out.</text>
<text x="44" y="102" font-size="17" fill="#52627e">Molecular drawings for Markdown and HTML. No TeX required.</text>
${cells.join('\n')}
<text x="44" y="611" font-size="13" fill="#52627e">Drawn by the renderer, from the same source as the interactive demo.</text>
</svg>
`,
);

const documentation = `# Example gallery

[Back to the README](../README.md)

These images are generated by the project's SVG renderer from the same examples used in the interactive demo. No TeX or external rendering service is involved.

Use a molecule body in a \`chemfig\` fence, an inline \`chemfig:\` code span, or \`renderChemfig(source)\`. Captions after the opening fence are supported by the **remark** plugin; the rehype plugin renders the structure but cannot recover captions discarded during Markdown-to-HTML conversion.

Regenerate this page and its images with \`bun run examples:build\`. Edit \`demo/examples.ts\`, not the generated files.

${examples
  .map(
    (example) => `## ${example.name}

![${example.name} molecular structure](../assets/examples/${slug(example.name)}.svg)

${example.note}

\`\`\`\`md
\`\`\`chemfig ${example.name}
${example.source}
\`\`\`
\`\`\`\`
`,
  )
  .join('\n')}`;
artifacts.set('docs/examples.md', documentation);

const stale: string[] = [];
for (const [path, content] of artifacts) {
  const url = new URL(path, root);
  if (check) {
    let current: string | undefined;
    try {
      current = await readFile(url, 'utf8');
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }
    if (current !== content) stale.push(path);
  } else {
    await mkdir(new URL('.', url), { recursive: true });
    await writeFile(url, content);
  }
}

if (stale.length) {
  console.error(`Out-of-date examples: ${stale.join(', ')}. Run bun run examples:build.`);
  process.exitCode = 1;
} else {
  console.log(`${check ? 'Verified' : 'Generated'} ${artifacts.size} example artifacts.`);
}
